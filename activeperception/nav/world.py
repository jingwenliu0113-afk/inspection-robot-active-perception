"""Gazebo Harmonic world for the B0 Nav2 runs (decision 015).

Same ground, light, pillars and fire hydrant as the Core world (``sim.sdf``), plus the
enclosure walls, the TurtleBot 4 world systems (IMU) and no free-flying inspector camera:
the camera rides on the robot's mast (``nav.robot``).
"""

from __future__ import annotations

from ..sim.sdf import LABEL_GROUND, WORLD_NAME, _inspector, _label_plugin, _object, _pillar
from ..types import Box, EpisodeSpec
from .scene import GENERATOR_VERSION, walls

LABEL_WALL = 40
NAV_SDF_VERSION = "sdf-nav-world-b0"


def _wall(i: int, box: Box) -> str:
    return f"""
    <model name="wall_{i}">
      <static>true</static>
      <pose>{box.cx:.6f} {box.cy:.6f} {box.cz:.6f} 0 0 0</pose>
      <link name="link">
        <collision name="collision"><geometry><box><size>{box.sx:.4f} {box.sy:.4f} {box.sz:.4f}</size></box></geometry></collision>
        <visual name="visual">
          <geometry><box><size>{box.sx:.4f} {box.sy:.4f} {box.sz:.4f}</size></box></geometry>
          <material><ambient>0.55 0.5 0.45 1</ambient><diffuse>0.6 0.55 0.5 1</diffuse></material>
          {_label_plugin(LABEL_WALL)}
        </visual>
      </link>
    </model>"""


def nav_world_sdf(spec: EpisodeSpec, teleport_camera_rate: float | None = None) -> str:
    """The Nav2 world; with ``teleport_camera_rate`` it instead carries the Core free-flying
    ``inspector_cam`` (no robot): the teleport reference render of the same scene (B1)."""
    lay = spec.layout
    pillars = "".join(_pillar(i, b) for i, b in enumerate(lay.occluders))
    enclosure = "".join(_wall(i, b) for i, b in enumerate(walls()))
    obj = (
        _object(lay.object_pose, lay.object_model) if lay.object_present and lay.object_pose else ""
    )
    cam = (
        _inspector(spec.initial_viewpoint.pose, spec.camera, teleport_camera_rate)
        if teleport_camera_rate
        else ""
    )
    return f"""<?xml version="1.0" ?>
<!-- generated by activeperception.nav.world ({NAV_SDF_VERSION}) for episode {spec.episode_id};
     generator {GENERATOR_VERSION}; seed {spec.seed}; do not edit by hand -->
<sdf version="1.9">
  <world name="{WORLD_NAME}">
    <physics name="3ms" type="ode"><max_step_size>0.003</max_step_size><real_time_factor>1.0</real_time_factor><real_time_update_rate>1000.0</real_time_update_rate></physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
      <background_color>0.6 0.7 0.8 1</background_color>
    </plugin>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <scene><ambient>0.6 0.6 0.6 1</ambient><background>0.6 0.7 0.8 1</background><shadows>false</shadows><grid>false</grid></scene>
    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse><specular>0.1 0.1 0.1 1</specular>
      <direction>-0.4 0.3 -0.9</direction>
    </light>
    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision"><geometry><plane><normal>0 0 1</normal><size>40 40</size></plane></geometry></collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>40 40</size></plane></geometry>
          <material><ambient>0.7 0.7 0.65 1</ambient><diffuse>0.75 0.75 0.7 1</diffuse></material>
          {_label_plugin(LABEL_GROUND)}
        </visual>
      </link>
    </model>{enclosure}{pillars}{obj}{cam}
  </world>
</sdf>
"""
