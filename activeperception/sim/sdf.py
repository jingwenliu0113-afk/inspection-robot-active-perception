"""Generate a Gazebo Harmonic SDF world from an ``EpisodeSpec``.

World contents: ground plane, sun, square occluder pillars, the target object
(``gazebo/models/<object_model>`` mesh, only when present) and an ``inspector_cam``
model carrying an RGB camera, a depth camera and a semantic segmentation camera, all
with identical intrinsics (``CameraModel``). Teleporting = ``/world/<world>/set_pose``
on ``inspector_cam``.

``clear=True`` drops the pillars: the GT pass that measures the unoccluded object
silhouette (decision 007).

Pose convention matches ``activeperception.types.Pose``: SDF ``x y z roll pitch yaw``
with roll = 0; camera optical axis along +x of the model frame, z up.
"""

from __future__ import annotations

import argparse
import xml.etree.ElementTree as ET
from pathlib import Path

from ..episodes import GeneratorConfig, generate_episode
from ..geometry import pose_quaternion
from ..types import Box, CameraModel, EpisodeSpec, Pose

WORLD_NAME = "inspection"
CAMERA_MODEL = "inspector_cam"
OBJECT_MODEL = "target_object"
PILLAR_PREFIX = "pillar_"
RGB_TOPIC = "/inspector/rgb"
DEPTH_TOPIC = "/inspector/depth"
SEG_TOPIC = "/inspector/segmentation"
LABEL_OBJECT = 10
LABEL_PILLAR = 20
LABEL_GROUND = 30
SDF_VERSION = "sdf-world-v2"


def pose_to_sdf(pose: Pose) -> str:
    return f"{pose.x:.6f} {pose.y:.6f} {pose.z:.6f} 0 {pose.pitch:.6f} {pose.yaw:.6f}"


def _label_plugin(label: int) -> str:
    return (
        f'<plugin filename="gz-sim-label-system" name="gz::sim::systems::Label">'
        f"<label>{label}</label></plugin>"
    )


def _pillar(i: int, box: Box) -> str:
    return f"""
    <model name="{PILLAR_PREFIX}{i}">
      <static>true</static>
      <pose>{box.cx:.6f} {box.cy:.6f} {box.cz:.6f} 0 0 0</pose>
      <link name="link">
        <collision name="collision"><geometry><box><size>{box.sx:.4f} {box.sy:.4f} {box.sz:.4f}</size></box></geometry></collision>
        <visual name="visual">
          <geometry><box><size>{box.sx:.4f} {box.sy:.4f} {box.sz:.4f}</size></box></geometry>
          <material><ambient>0.45 0.45 0.45 1</ambient><diffuse>0.5 0.5 0.5 1</diffuse></material>
          {_label_plugin(LABEL_PILLAR)}
        </visual>
      </link>
    </model>"""


def _object(pose: Pose, model: str) -> str:
    return f"""
    <model name="{OBJECT_MODEL}">
      <static>true</static>
      <pose>{pose.x:.6f} {pose.y:.6f} {pose.z:.6f} 0 0 {pose.yaw:.6f}</pose>
      <link name="link">
        <visual name="visual">
          <geometry><mesh><uri>model://{model}/meshes/{model}.dae</uri></mesh></geometry>
          {_label_plugin(LABEL_OBJECT)}
        </visual>
      </link>
    </model>"""


def _camera_block(camera: CameraModel) -> str:
    return f"""<camera>
            <horizontal_fov>{camera.hfov:.6f}</horizontal_fov>
            <image><width>{camera.width}</width><height>{camera.height}</height></image>
            <clip><near>0.05</near><far>20</far></clip>
          </camera>"""


def _inspector(pose: Pose, camera: CameraModel, update_rate: float) -> str:
    cam = _camera_block(camera)
    return f"""
    <model name="{CAMERA_MODEL}">
      <static>true</static>
      <pose>{pose_to_sdf(pose)}</pose>
      <link name="link">
        <sensor name="rgb" type="camera">
          <always_on>true</always_on><update_rate>{update_rate}</update_rate><visualize>false</visualize>
          <topic>{RGB_TOPIC}</topic>
          {cam}
        </sensor>
        <sensor name="depth" type="depth_camera">
          <always_on>true</always_on><update_rate>{update_rate}</update_rate><visualize>false</visualize>
          <topic>{DEPTH_TOPIC}</topic>
          {cam}
        </sensor>
        <sensor name="segmentation" type="segmentation_camera">
          <always_on>true</always_on><update_rate>{update_rate}</update_rate><visualize>false</visualize>
          <topic>{SEG_TOPIC}</topic>
          {cam.replace("<camera>", "<camera><segmentation_type>semantic</segmentation_type>")}
        </sensor>
      </link>
    </model>"""


def world_sdf(
    spec: EpisodeSpec,
    render_engine: str = "ogre2",
    update_rate: float = 10.0,
    clear: bool = False,
) -> str:
    lay = spec.layout
    pillars = "" if clear else "".join(_pillar(i, b) for i, b in enumerate(lay.occluders))
    obj = (
        _object(lay.object_pose, lay.object_model) if lay.object_present and lay.object_pose else ""
    )
    inspector = _inspector(spec.initial_viewpoint.pose, spec.camera, update_rate)
    return f"""<?xml version="1.0" ?>
<!-- generated by activeperception.sim.sdf ({SDF_VERSION}) for episode {spec.episode_id};
     generator {spec.generator_version}; seed {spec.seed}; pass {"clear" if clear else "full"};
     do not edit by hand -->
<sdf version="1.9">
  <world name="{WORLD_NAME}">
    <physics name="default" type="ode"><max_step_size>0.004</max_step_size><real_time_factor>1.0</real_time_factor></physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>{render_engine}</render_engine>
      <background_color>0.6 0.7 0.8 1</background_color>
    </plugin>
    <scene><ambient>0.6 0.6 0.6 1</ambient><background>0.6 0.7 0.8 1</background><shadows>false</shadows></scene>
    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse><specular>0.1 0.1 0.1 1</specular>
      <direction>-0.4 0.3 -0.9</direction>
    </light>
    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision"><geometry><plane><normal>0 0 1</normal><size>40 40</size></plane></geometry></collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>40 40</size></plane></geometry>
          <material><ambient>0.7 0.7 0.65 1</ambient><diffuse>0.75 0.75 0.7 1</diffuse></material>
          {_label_plugin(LABEL_GROUND)}
        </visual>
      </link>
    </model>{pillars}{obj}{inspector}
  </world>
</sdf>
"""


def set_pose_request(pose: Pose, model: str = CAMERA_MODEL) -> str:
    """Text protobuf for ``gz service -s /world/<world>/set_pose --reqtype gz.msgs.Pose``."""
    w, x, y, z = pose_quaternion(pose.yaw, pose.pitch)
    return (
        f'name: "{model}", position: {{x: {pose.x:.6f}, y: {pose.y:.6f}, z: {pose.z:.6f}}}, '
        f"orientation: {{x: {x:.6f}, y: {y:.6f}, z: {z:.6f}, w: {w:.6f}}}"
    )


def validate(sdf_text: str) -> ET.Element:
    root = ET.fromstring(sdf_text)
    if root.tag != "sdf":
        raise ValueError("root must be <sdf>")
    return root


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="activeperception.sim.sdf")
    ap.add_argument("--namespace", required=True)
    ap.add_argument("--group", type=int, required=True)
    ap.add_argument("--variant", type=int, default=0)
    ap.add_argument("--render-engine", default="ogre2")
    ap.add_argument("--clear", action="store_true", help="GT pass: no pillars")
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)
    spec = generate_episode(args.namespace, args.group, args.variant, GeneratorConfig())
    text = world_sdf(spec, render_engine=args.render_engine, clear=args.clear)
    validate(text)
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(text)
    print(
        f"wrote {args.out} for {spec.episode_id} (present={spec.layout.object_present}, pillars={len(spec.layout.occluders)})"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
